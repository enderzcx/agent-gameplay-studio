#!/usr/bin/env python3
"""Offline tests for skills/gameplay-postproduction/scripts/check_postproduction.py.

Everything here is deterministic and needs no model, no network, no credentials and no fixture
media committed to the repo. The only external dependency is `ffmpeg`/`ffprobe`, and only for the
`ready`-mode cases, which build a throwaway MP4 in a temp directory.

Run:  python3 tests/test_check_postproduction.py
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CHECKER = ROOT / "skills" / "gameplay-postproduction" / "scripts" / "check_postproduction.py"
AUDIT_SCRIPT = ROOT / "skills" / "gameplay-postproduction" / "scripts" / "check_timeline_audit.py"
EXAMPLES = ROOT / "examples"

PASS = 0
FAIL = 0


def run(mode: str, target: Path, *extra: str) -> tuple[int, dict]:
    p = subprocess.run([sys.executable, str(CHECKER), mode, str(target), "--json", *extra],
                       capture_output=True, text=True)
    try:
        payload = json.loads(p.stdout or "{}")
    except json.JSONDecodeError:
        payload = {"_raw": p.stdout, "_stderr": p.stderr}
    return p.returncode, payload


def expect(name: str, want_rc: int, mode: str, target: Path, *extra: str,
           substr: str | None = None) -> dict:
    global PASS, FAIL
    rc, payload = run(mode, target, *extra)
    detail = ""
    ok = rc == want_rc
    if ok and substr is not None:
        blob = json.dumps(payload, ensure_ascii=False)
        ok = substr in blob
        detail = f"（未在输出里找到 {substr!r}）" if not ok else ""
    if ok:
        print(f"ok  {name}")
        PASS += 1
    else:
        print(f"FAIL {name}: rc={rc} want={want_rc} {detail}")
        print(f"     payload={json.dumps(payload, ensure_ascii=False)[:400]}")
        FAIL += 1
    return payload


def write(p: Path, text: str) -> Path:
    p.write_text(text, encoding="utf-8")
    return p


